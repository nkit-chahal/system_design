import os
import glob
import re
import json

DIRS = [
    'Behavioral Interview',
    'Coding Interview Patterns',
    'Generative AI System Design Interview',
    'Machine Learning System Design Interview',
    'Mobile System Design Interview',
    'Object-Oriented Design Interview',
    'System Design Interview'
]

# Category Display Names & Icons
CATEGORY_META = {
    'Behavioral Interview': {'name': 'Behavioral Interview', 'icon': '👥', 'color': '#f59e0b'},
    'Coding Interview Patterns': {'name': 'Coding Interview Patterns', 'icon': '⚡', 'color': '#3b82f6'},
    'Generative AI System Design Interview': {'name': 'Generative AI System Design', 'icon': '🤖', 'color': '#8b5cf6'},
    'Machine Learning System Design Interview': {'name': 'ML System Design', 'icon': '📊', 'color': '#10b981'},
    'Mobile System Design Interview': {'name': 'Mobile System Design', 'icon': '📱', 'color': '#06b6d4'},
    'Object-Oriented Design Interview': {'name': 'Object-Oriented Design', 'icon': '🧩', 'color': '#f43f5e'},
    'System Design Interview': {'name': 'System Design Interview', 'icon': '🏗️', 'color': '#ec4899'}
}

def generate_unified_nav_data():
    all_lessons = []
    category_tree = {}
    path_to_lesson = {}
    
    for dir_name in DIRS:
        files = sorted(glob.glob(os.path.join(dir_name, '*.html')))
        current_subgroup = 'General'
        category_tree[dir_name] = {}
        
        for f in files:
            fname = os.path.basename(f)
            rel_path = f"{dir_name}/{fname}".replace('\\', '/')
            
            # Extract number prefix
            m = re.match(r'^(\d+)[.\s]*(.*)\.html$', fname, re.IGNORECASE)
            if m:
                num = int(m.group(1))
                raw_title = m.group(2).strip()
            else:
                num = 0
                raw_title = fname.replace('.html', '').strip()
            
            clean_title = raw_title
            
            # Determine subgroup for Coding Patterns
            if dir_name == 'Coding Interview Patterns':
                if clean_title.lower().startswith('introduction to '):
                    current_subgroup = clean_title[15:].strip()
                elif clean_title.lower() == 'introduction':
                    current_subgroup = 'General'
            else:
                current_subgroup = 'General'
                
            lesson_obj = {
                'category': dir_name,
                'subgroup': current_subgroup,
                'num': num,
                'title': clean_title,
                'filename': fname,
                'path': rel_path
            }
            
            all_lessons.append(lesson_obj)
            path_to_lesson[rel_path] = lesson_obj
            
            if current_subgroup not in category_tree[dir_name]:
                category_tree[dir_name][current_subgroup] = []
            category_tree[dir_name][current_subgroup].append(lesson_obj)

    js_content = f"""// Auto-generated by build_unified_nav_data.py
const NAV_LESSONS = {json.dumps(all_lessons, indent=2)};
const NAV_TREE = {json.dumps(category_tree, indent=2)};
const NAV_META = {json.dumps(CATEGORY_META, indent=2)};
"""
    
    with open('nav_map.js', 'w', encoding='utf-8') as f:
        f.write(js_content)
        
    print(f"Generated nav_map.js with {len(all_lessons)} lessons across {len(category_tree)} categories.")

if __name__ == '__main__':
    generate_unified_nav_data()
