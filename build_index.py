import os, glob, re, json

DIRS = [
    'Python Course',
    'AI Inference Engineering',
    'Behavioral Interview',
    'Coding Interview Patterns',
    'Generative AI System Design Interview',
    'Machine Learning System Design Interview',
    'Mobile System Design Interview',
    'Object-Oriented Design Interview',
    'System Design Interview'
]

CATEGORY_COLORS = {
    'Python Course': '#05673d',
    'AI Inference Engineering': '#0ea5e9',
    'Behavioral Interview': '#f59e0b',
    'Coding Interview Patterns': '#3b82f6',
    'Generative AI System Design Interview': '#8b5cf6',
    'Machine Learning System Design Interview': '#10b981',
    'Mobile System Design Interview': '#06b6d4',
    'Object-Oriented Design Interview': '#f43f5e',
    'System Design Interview': '#ec4899'
}

def generate_index():
    data = []
    for dir_name in DIRS:
        files = sorted(glob.glob(os.path.join(dir_name, '*.html')))
        current_subgroup = 'General'
        # Generated courses can declare groups (e.g. stages) in course.json
        course_meta_path = os.path.join(dir_name, 'course.json')
        declared_subgroups = {}
        if os.path.exists(course_meta_path):
            with open(course_meta_path, encoding='utf-8') as meta_file:
                declared_subgroups = json.load(meta_file).get('subgroups', {})
        for f in files:
            fname = os.path.basename(f)
            if fname.lower() == 'index.html':
                continue
            m = re.match(r'^(\d+)[.\s]*(.*)\.html$', fname, re.IGNORECASE)
            if m:
                num = int(m.group(1))
                raw_title = m.group(2).strip()
            else:
                num = 0
                raw_title = fname.replace('.html', '').strip()
            clean_title = raw_title
            if dir_name == 'Coding Interview Patterns':
                if clean_title.lower().startswith('introduction to '):
                    current_subgroup = clean_title[15:].strip()
                elif clean_title.lower() == 'introduction':
                    current_subgroup = 'General'
            else:
                current_subgroup = declared_subgroups.get(fname, dir_name)
            size_bytes = os.path.getsize(f)
            size_kb = round(size_bytes / 1024, 1)
            read_time = max(3, min(30, int(size_kb / 150) + 4))
            rel_path = dir_name + '/' + fname
            cat_slug = dir_name.lower().replace(' ', '-')
            data.append({
                'id': cat_slug + '-' + str(num),
                'category': dir_name,
                'subgroup': current_subgroup,
                'num': num,
                'title': clean_title,
                'filename': fname,
                'path': rel_path,
                'sizeKb': size_kb,
                'readTimeMin': read_time,
                'color': CATEGORY_COLORS.get(dir_name, '#3b82f6')
            })
    js_content = '// Auto-generated by build_index.py\nconst LESSONS_DATA = ' + json.dumps(data, indent=2) + ';\n'
    with open('lessons_data.js', 'w', encoding='utf-8') as out_file:
        out_file.write(js_content)
    print('Generated lessons_data.js with ' + str(len(data)) + ' lessons.')

if __name__ == '__main__':
    generate_index()
